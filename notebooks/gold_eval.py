"""Evaluate the recommender against an independently annotated reference set.

Why this matters
----------------
Every previous metric in this project was computed against ``occ_*`` columns
generated by ``configs/taxonomy.yaml`` — the same rules the engine ranks on.
Measuring a system against its own rules is a consistency check, not an
evaluation: a rule engine scores perfectly against itself by construction.

``gold_test_labelled.csv`` was produced by a separate annotator that reads
sub-category, product name and price, and never reads ``category`` or any
``occ_*`` column. Its labels are therefore independent of the ranking signal,
which makes Precision@K and NDCG@K computed here meaningful rather than
circular.

Label provenance is machine, not human — see docs/decisions/0007. These figures
measure agreement with an independent method, not accuracy against human
judgement, and must be reported that way.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

OCCASIONS = ["Birthday", "Graduation", "Anniversary", "Wedding", "Eid",
             "MothersDay", "FathersDay", "NewBaby", "Housewarming", "ThankYou"]


def dcg(relevances: np.ndarray) -> float:
    """Discounted cumulative gain of a ranked relevance vector."""
    return float(np.sum(relevances / np.log2(np.arange(2, len(relevances) + 2))))


def ndcg_at_k(relevances: np.ndarray, k: int) -> float:
    """Normalised DCG: actual gain over the gain of a perfect ordering."""
    actual = dcg(relevances[:k])
    ideal = dcg(np.sort(relevances)[::-1][:k])
    return actual / ideal if ideal > 0 else 0.0


def evaluate(recommender, catalog: pd.DataFrame, gold: pd.DataFrame,
             k_values=(1, 3, 5, 10), n_queries: int = 400,
             seed: int = 42) -> pd.DataFrame:
    """Score the engine on the judged subset, using pooled evaluation.

    A live top-10 over 45,055 products almost never intersects a 300-item
    reference set, which leaves too few judged results to measure anything.
    Pooled evaluation is the standard answer: restrict the candidate pool to
    items an annotator actually judged, rank those, and ask whether the engine
    places the relevant ones above the irrelevant ones.

    This measures **ranking quality**, which is the thing the engine controls.
    It does not measure retrieval over the full catalogue, and should not be
    reported as if it did.
    """
    rng = np.random.default_rng(seed)
    gold = gold.dropna(subset=["parent_id"]).copy()
    truth = {occ: set(gold.loc[gold[occ] == 1, "parent_id"]) for occ in OCCASIONS}
    gold_ids = set(gold["parent_id"])

    meta = catalog.set_index("parent_id")
    rows = []

    for occ in OCCASIONS:
        pool = gold[gold[occ] == 1]
        if len(pool) < 3:
            continue
        for _ in range(max(1, n_queries // len(OCCASIONS))):
            seed_row = pool.sample(1, random_state=int(rng.integers(1e9))).iloc[0]
            pid = seed_row["parent_id"]
            if pid not in meta.index:
                continue
            item = meta.loc[pid]
            age = int(np.clip((item["min_age"] + min(item["max_age"], 70)) / 2, 1, 80))
            # Generous budget so the pool is not truncated by the hard filter:
            # this experiment isolates ranking, not admissibility.
            budget = 100_000.0
            gender = item["gender_target"] if item["gender_target"] != "Unisex" else "Any"

            ranked = recommender.rank_subset(
                candidate_ids=list(gold_ids), age=age, gender=gender,
                occasion=occ, budget=budget, interests=[],
            )
            if len(ranked) < max(k_values):
                continue
            rel = ranked.parent_id.isin(truth[occ]).to_numpy().astype(float)

            rec = {"occasion": occ, "n_judged": len(rel)}
            for k in k_values:
                rec[f"P@{k}"] = float(rel[:k].mean()) if len(rel) >= 1 else np.nan
                rec[f"NDCG@{k}"] = ndcg_at_k(rel, k)
            rows.append(rec)

    return pd.DataFrame(rows)


def summarise(results: pd.DataFrame, k_values=(1, 3, 5, 10)) -> pd.DataFrame:
    """Aggregate per-occasion and overall."""
    cols = [f"P@{k}" for k in k_values] + [f"NDCG@{k}" for k in k_values]
    per_occ = results.groupby("occasion")[cols].mean().round(3)
    per_occ.loc["OVERALL"] = results[cols].mean().round(3)
    per_occ["queries"] = results.groupby("occasion").size().reindex(per_occ.index)
    per_occ.loc["OVERALL", "queries"] = len(results)
    return per_occ
